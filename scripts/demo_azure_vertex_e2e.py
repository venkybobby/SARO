#!/usr/bin/env python3
"""Azure OpenAI + Vertex AI end-to-end observation demo runner.

Walks SARO's observation pipeline live, per provider, in five staged steps:

    [1/5] read the customer-owned log export        (read-only, INV-6)
    [2/5] adapter parse -> NormalizedInvocationRecord
    [3/5] contract invariants (body-free, availability honesty)
    [4/5] observation rule-pack evaluation -> findings
    [5/5] evidence summary (+ optional JSON artifact)

Everything runs offline against the committed deterministic corpora
(`tests/fixtures/azure/corpus.ndjson`, `tests/fixtures/vertex/corpus.ndjson`) —
the same bytes CI verifies. Zero network, zero cloud credentials, zero model
calls (INV-1), zero writes outside the optional ``--json-out`` path. The output
is deterministic so the committed screencast (docs/demo/) reproduces exactly.

Cloud-side setup for a *real* export (Azure Diagnostic Settings, GCP audit-log
sink) is documented in docs/demo/AZURE_VERTEX_E2E_DEMO.md — that part happens
in the customer's cloud account, never inside SARO.

Usage:
    python scripts/demo_azure_vertex_e2e.py                 # both providers
    python scripts/demo_azure_vertex_e2e.py --provider azure
    python scripts/demo_azure_vertex_e2e.py --json-out artifacts/demo.json
    python scripts/demo_azure_vertex_e2e.py --pace 0.6      # paced, for capture
"""

